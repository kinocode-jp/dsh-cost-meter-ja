    /** 探测浏览器语言:zh* → zh,其余 → en。 */
    function detectBrowserLocale() {
      const lang = typeof navigator !== 'undefined' && typeof navigator.language === 'string' ? navigator.language : ''
      const lower = lang.toLowerCase()
      if (lower.startsWith('ja')) return 'ja'
      return lower.startsWith('zh') ? 'zh' : 'en'
    }

    /** 显式插件语言优先;auto 使用当前 DSH 语言,旧宿主回退浏览器。 */
    function supportedLocale(value) {
      const lang = typeof value === 'string' ? value.toLowerCase().split(/[-_]/)[0] : ''
      return lang === 'zh' || lang === 'en' || lang === 'ja' ? lang : null
    }
    function resolveLocale(config) {
      const value = typeof config === 'string' ? config : config?.locale
      if (value === 'zh' || value === 'en' || value === 'ja') return value
      return supportedLocale(config?.activeLocale) || detectBrowserLocale()
    }

    /** 构造按当前语言取文案的函数 t(key, vars)。 */
    function makeT(locale) {
      const dict = locale === 'zh' ? MESSAGES.zh : locale === 'ja' ? MESSAGES.ja : MESSAGES.en
      return (key, vars) => {
        let text = dict[key] ?? MESSAGES.en[key] ?? key
        if (vars) for (const name of Object.keys(vars)) text = text.split('{' + name + '}').join(String(vars[name]))
        return text
      }
    }

